import { Router } from 'express';
import { requireAuth } from '../middleware/auth';
import { listRecipients, updateRecipient, deleteRecipient, bulkDeleteRecipients } from '../controllers/recipientController';
const router = Router();
router.use(requireAuth);
router.get('/', listRecipients);
router.patch('/:id', updateRecipient);
router.delete('/:id', deleteRecipient);
router.post('/bulk-delete', bulkDeleteRecipients);
export default router;
